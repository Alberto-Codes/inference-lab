"""Generate eight original, deterministic RGB documents with known text.

Examples:
    Create a corpus in a chosen output directory:

    ```python
    from pathlib import Path
    from inference_lab.corpus import generate

    count = generate(Path("corpus"))
    ```

See Also:
    [`inference_lab.experiment.load_corpus`][]: Read and prepare generated images.
"""

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def generate(directory: Path) -> int:
    """Write synthetic page images and their expected-text manifest.

    Existing generated filenames and the manifest are replaced.

    Args:
        directory: Destination directory, created with any missing parents.

    Returns:
        Number of generated pages, always eight.
    """
    directory.mkdir(parents=True, exist_ok=True)
    pages = []
    font = ImageFont.load_default(size=32)
    for index in range(8):
        lines = [
            f"INFERENCE LAB PAGE {index + 1}",
            "Synthetic inventory record",
            f"Item: cobalt notebook {index + 1}",
            f"Quantity: {12 + index}",
            f"Reference: LAB{401 + index}",
            "All entries are fictional.",
        ]
        image = Image.new("RGB", (1000, 1200), "white")
        draw = ImageDraw.Draw(image)
        for row, line in enumerate(lines):
            draw.text((70, 80 + row * 100), line, fill="black", font=font)
        filename = f"page-{index + 1:02}.png"
        image.save(directory / filename)
        pages.append({"file": filename, "expected": lines})
    (directory / "manifest.json").write_text(
        json.dumps(
            {
                "provenance": (
                    "Original synthetic text and layout generated by inference-lab; "
                    "CC0-1.0. Pillow bundled default font."
                ),
                "pages": pages,
            },
            indent=2,
        )
        + "\n"
    )
    return len(pages)
